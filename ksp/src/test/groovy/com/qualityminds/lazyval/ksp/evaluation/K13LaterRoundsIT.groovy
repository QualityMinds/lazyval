package com.qualityminds.lazyval.ksp.evaluation

import com.qualityminds.lazyval.testkit.Testkit
import com.qualityminds.lazyval.testkit.Testresult
import com.qualityminds.lazyval.testkit.dependencies.Dependency
import com.qualityminds.lazyval.testkit.scenarios.Scenario
import spock.lang.Shared
import spock.lang.Specification
import spock.lang.TempDir
import spock.lang.Title

import java.nio.file.Path

/**
 * AI evaluation finding K13 (GitHub issue "Evaluation: ksp", label evaluation). This specification intentionally
 * fails on main: it documents the expected behaviour, not the current one.
 * <p>
 * {@code LazyvalSymbolProcessor} sets {@code hasProcessed = true} after the first round and returns no deferred
 * symbols, so a {@code @LazyValue} type that appears in a later round, generated by another processor or by a
 * Lazyval generator, is never generated for. The test-only {@link RoundTwoProbeGenerator} emits such a type in
 * round one; on main its JPA converter is missing although the build succeeds.
 */
@Title("Evaluation K13 - later rounds are ignored")
class K13LaterRoundsIT extends Specification {

    static final Dependency JPA = new Dependency("jakarta.persistence", "jakarta.persistence-api", "3.2.0")

    @TempDir
    Path projectDir

    @Shared
    def testkitKotlin = Testkit.kotlin()

    void "K13 a @LazyValue type generated in the first round gets its converter in the next round"() {
        given: 'a seed domain-primitive and the probe that generates RoundTwo while processing it'
        def scenario = Scenario.Kotlin.of("round-two probe",
                "scenarios/evaluation/k13/Seed.kt",
                "scenarios/evaluation/k13/RoundTwoProbe.kt")
                .withDependencies(JPA)

        when:
        def result = testkitKotlin.run(projectDir, scenario)

        then:
        result instanceof Testresult.Kotlin.Success
        def generatedFiles = (result as Testresult.Kotlin.Success).generatedFiles()

        and: 'precondition: the probe ran and the first round was generated for'
        generatedFiles.contains("RoundTwo.kt")
        generatedFiles.contains("SeedAttributeConverter.kt")

        and: 'the type of the second round is generated for as well'
        generatedFiles.contains("RoundTwoAttributeConverter.kt")
    }
}
